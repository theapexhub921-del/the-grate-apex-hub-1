"""Write src/data/figures/pictures/<topic>.ts from built/<topic>.json."""
import json, os, re, sys

REPO = os.environ.get('GRATEAPEX_REPO', '../..')
SOURCE = {'cvs': 'anat-cvs-gross-1', 'resp': 'anat-respiratory-gross', 'abdwall': 'anat-abdominal-walls',
          'gitract': 'anat-gi-tract-organs', 'ginv': 'anat-gi-neurovasculature', 'urinary': 'anat-urinary-gross',
          'ul': 'anat-upper-limbs-updated', 'hn': 'anat-head-neck', 'cns': 'anat-cns', 'meninges': 'anat-meninges',
          'cvs2': 'cardiovascular-gross-slides'}
lessons = {l['lesson']: l for l in json.load(open('lessons.json'))}
os.makedirs(f'{REPO}/src/data/figures/pictures', exist_ok=True)


def nearest(items, src, slide):
    """Index of the item whose slide refs (same deck) are nearest to `slide`."""
    best, best_d = None, None
    for it in items:
        ns = [n for s, n in it['slides'] if s == src]
        if not ns:
            continue
        d = min(abs(n - slide) for n in ns)
        if best_d is None or d < best_d:
            best, best_d = it, d
    return best


def camel(name):
    parts = name.split('-')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def js(v):
    return json.dumps(v, ensure_ascii=False)


for topic in sys.argv[1:]:
    built = json.load(open(f'built/{topic}.json'))
    specs = [s['name'] for s in json.load(open(f'specs/{topic}.json'))]
    out = [f"// Lecture pictures for the {topic.replace('-', ' ')} lessons: crops of the",
           "// lecture slides' own diagrams. Each picture's labels are the ones printed",
           "// on the slide (read from the slide image, spelling tidied); pins sit where",
           "// each label's leader line starts, and the labels are covered in",
           "// \"Test yourself\" and in the quiz questions.",
           "// Generated by the picture pipeline (see docs/lesson-pictures.md); placed",
           "// in lessons by buildTopic (`pictures`). Images: public/figures/" + topic + "/.",
           "import type { LessonFigure } from '@/data/lesson-types';",
           "import type { PicturePlacement } from '@/data/topics/build';", ""]
    names = []
    placements = []
    for name in specs:
        f = built[name]
        src = SOURCE[f['deck']]
        les = lessons[f['lesson']]
        chunk = f['chunk'] if f.get('chunk') is not None else nearest(les['chunks'], src, f['slide'])['i'] if nearest(les['chunks'], src, f['slide']) else 0
        step_item = nearest(les['steps'], src, f['slide'])
        step = f['step'] if f.get('step') is not None else (step_item['i'] if step_item else (les['steps'][0]['i'] if les['steps'] else None))
        concept_item = nearest(les['concepts'], src, f['slide'])
        concept = f['concept'] or (concept_item['id'] if concept_item else les['concepts'][0]['id'])
        var = camel(name)
        names.append(var)
        caption = f.get('caption') or f"From lecture slide {f['slide']}."
        out.append(f"export const {var}: LessonFigure = {{")
        out.append(f"  id: {js(topic + ':' + name)},")
        out.append(f"  title: {js(f['title'])},")
        out.append(f"  src: {js(f'/figures/{topic}/{name}.jpg')},")
        out.append(f"  width: {f['width']},")
        out.append(f"  height: {f['height']},")
        out.append(f"  caption: {js(caption)},")
        out.append(f"  sourceRefs: [{{ sourceId: {js(src)}, slide: {f['slide']}, visual: true }}],")
        out.append("  spots: [")
        for s in f['spots']:
            parts = [f"id: {js(s['id'])}", f"label: {js(s['label'])}"]
            if s.get('note'):
                parts.append(f"note: {js(s['note'])}")
            parts += [f"x: {s['x']}", f"y: {s['y']}"]
            if s.get('boxes'):
                parts.append(f"boxes: {js(s['boxes'])}")
            out.append("    { " + ", ".join(parts) + " },")
        out.append("  ],")
        out.append("};")
        out.append("")
        ids = [s['id'] for s in f['spots']]
        norm = lambda t: re.sub(r'[^a-z0-9]', '', t)[:32]
        by_norm = {norm(i): i for i in ids}
        quiz = [q if q in ids else by_norm.get(norm(q)) for q in (f.get('quiz') or [])]
        quiz = [q for q in quiz if q]
        missing = [] if len(quiz) == len(f.get('quiz') or []) else ['?']
        if missing:
            print('WARN missing quiz spots', topic, name, missing)
        placements.append(f"  {{ figure: {var}, lessonId: {js(f['lesson'])}, chunk: {chunk}" +
                          (f", step: {step}" if step is not None else "") +
                          f", conceptId: {js(concept)}, quiz: {js(quiz)} }},")
    out.append(f"export const figures: LessonFigure[] = [{', '.join(names)}];")
    out.append("")
    out.append("export const pictures: PicturePlacement[] = [")
    out += placements
    out.append("];")
    open(f'{REPO}/src/data/figures/pictures/{topic}.ts', 'w').write('\n'.join(out) + '\n')
    print(topic, len(names))
